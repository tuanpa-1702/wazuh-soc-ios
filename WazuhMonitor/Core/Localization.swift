import Foundation

/// Ngôn ngữ giao diện (lưu trong UserDefaults "app.lang").
enum AppLanguage: String, CaseIterable, Identifiable {
    case vi, en
    var id: String { rawValue }
    var title: String { self == .vi ? "Tiếng Việt" : "English" }
    var locale: Locale { Locale(identifier: self == .vi ? "vi_VN" : "en_US") }

    static let storageKey = "app.lang"
    static var current: AppLanguage {
        AppLanguage(rawValue: UserDefaults.standard.string(forKey: storageKey) ?? "") ?? .vi
    }
}

/// Chế độ giao diện (lưu trong UserDefaults "app.appearance").
enum AppAppearance: String, CaseIterable, Identifiable {
    case system, light, dark
    var id: String { rawValue }
    static let storageKey = "app.appearance"
    var title: String {
        switch self {
        case .system: return L("Tự động")
        case .light: return L("Sáng")
        case .dark: return L("Tối")
        }
    }
    var icon: String {
        switch self {
        case .system: return "circle.lefthalf.filled"
        case .light: return "sun.max.fill"
        case .dark: return "moon.fill"
        }
    }
}

/// Dịch một chuỗi gốc tiếng Việt sang ngôn ngữ đang chọn.
func L(_ vi: String) -> String {
    guard AppLanguage.current == .en else { return vi }
    return EN[vi] ?? vi
}

/// Dịch chuỗi có tham số dạng {0}, {1}…
func Lf(_ vi: String, _ args: String...) -> String {
    var s = L(vi)
    for (i, a) in args.enumerated() { s = s.replacingOccurrences(of: "{\(i)}", with: a) }
    return s
}

